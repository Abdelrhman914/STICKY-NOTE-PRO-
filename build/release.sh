#!/usr/bin/env bash
# ==========================================================================
#  StickyNotes Pro — signed release pipeline
#
#  1. Creates (once) or reuses the release code-signing certificate
#     (or uses a real CA-issued one: SNP_PFX + SNP_PFX_PASS_FILE).
#  2. Pins the certificate SHA-256 into src/Security/SigningPin.g.cs.
#  3. Builds the app (warnings as errors) and signs + timestamps the exe.
#  4. Verifies with osslsigncode AND with the IntegrityVerifier tool
#     (the exact same verifier code the app runs at start-up).
#  5. Tamper tests: patched byte / appended data / unsigned / foreign cert
#     with the same CN must ALL be rejected.
#  5b. Builds + signs the NSIS installer (and its uninstaller).
#  6. Writes release/<version>/: binaries, SHA256SUMS, manifest JSON and
#     the digitally signed Certificate-of-Integrity PDF.
# ==========================================================================
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="$ROOT/build"
SRC="$ROOT/src"
OUT="${SNP_OUT:-$HOME/.cache/out}"
PY="${SNP_PYTHON:-python3}"
export SNP_TSA="${SNP_TSA:-http://timestamp.digicert.com}"
mkdir -p "$OUT"

VERSION="$(grep -m1 -oP '(?<=<Version>)[^<]+' "$SRC/StickyNotesPro.csproj")"
echo "== StickyNotes Pro $VERSION – signed release build"

# ---------------------------------------------------------------- signing certificate
if [ -z "$SNP_PFX" ]; then
    SD="$ROOT/signing"
    mkdir -p "$SD"; chmod 700 "$SD"
    if [ ! -f "$SD/StickyNotesPro-CodeSigning.pfx" ]; then
        echo "-- creating self-signed release code-signing certificate (RSA-3072, 5 years)"
        openssl genrsa -out "$SD/key.pem" 3072 2>/dev/null
        openssl req -new -x509 -key "$SD/key.pem" -out "$SD/StickyNotesPro-CodeSigning.pem" \
            -days 1826 -config "$SD/codesign.cnf" -extensions v3_codesign 2>/dev/null \
            || openssl req -new -x509 -key "$SD/key.pem" -out "$SD/StickyNotesPro-CodeSigning.pem" -days 1826 \
                -subj "/C=EG/L=Cairo/O=StickyNotes Pro/OU=Release Engineering/CN=StickyNotes Pro Release Signing" \
                -addext "basicConstraints=critical,CA:FALSE" -addext "keyUsage=critical,digitalSignature" \
                -addext "extendedKeyUsage=critical,codeSigning" 2>/dev/null
        PW="$(openssl rand -hex 24)"; echo "$PW" > "$SD/pfx-password.txt"
        openssl pkcs12 -export -out "$SD/StickyNotesPro-CodeSigning.pfx" \
            -inkey "$SD/key.pem" -in "$SD/StickyNotesPro-CodeSigning.pem" \
            -passout file:"$SD/pfx-password.txt" \
            -keypbe AES-256-CBC -certpbe AES-256-CBC -name "StickyNotes Pro Release Signing"
        shred -u "$SD/key.pem" 2>/dev/null || rm -f "$SD/key.pem"
    fi
    export SNP_PFX="$SD/StickyNotesPro-CodeSigning.pfx"
    export SNP_PFX_PASS_FILE="$SD/pfx-password.txt"
fi

CERT_TMP="$(mktemp)"
openssl pkcs12 -in "$SNP_PFX" -passin file:"$SNP_PFX_PASS_FILE" -clcerts -nokeys 2>/dev/null \
    | openssl x509 -out "$CERT_TMP"
PIN="$(openssl x509 -in "$CERT_TMP" -outform DER | sha256sum | awk '{print toupper($1)}')"
SUBJ="$(openssl x509 -in "$CERT_TMP" -noout -subject | sed 's/^subject=//')"
echo "-- signing certificate: $SUBJ"
echo "-- pinned SHA-256     : $PIN"

# pin the certificate into the binary
cat > "$SRC/Security/SigningPin.g.cs" <<EOF
// <auto-generated>
//   Written by build/release.sh from the release signing certificate. Do not edit by hand.
//   Certificate: $SUBJ
// </auto-generated>
namespace StickyNotesPro.Security
{
    internal static class SigningPin
    {
        /// <summary>SHA-256 of the DER-encoded release code-signing certificate.</summary>
        public const string CertSha256 = "$PIN";
        public const bool Enforce = true;
    }
}
EOF

# ---------------------------------------------------------------- build + sign
echo "-- building"
rm -f "$OUT/StickyNotesPro.exe"
( cd "$SRC" && dotnet build -c Release -o "$OUT" -nologo -clp:NoSummary -warnaserror | grep -E "error|warn" || true ; rm -rf bin obj )
[ -f "$OUT/StickyNotesPro.exe" ] || { echo "build FAILED"; exit 1; }

bash "$BUILD/sign-file.sh" "$OUT/StickyNotesPro.exe"

# ---------------------------------------------------------------- verify (build gate)
echo "-- verifying"
osslsigncode verify -CAfile "$CERT_TMP" -in "$OUT/StickyNotesPro.exe" > "$OUT/verify.txt" 2>&1 \
    || { cat "$OUT/verify.txt"; echo "osslsigncode verification FAILED"; exit 1; }
VT="$BUILD/tools/IntegrityVerifier"
rm -rf "$HOME/.cache/ivtool"
( cd "$VT" && ( dotnet build -c Release -o "$HOME/.cache/ivtool" -nologo -v q 2>&1 | grep -E " error " || true ); rm -rf bin obj )
[ -f "$HOME/.cache/ivtool/IntegrityVerifier.dll" ] || { echo "IntegrityVerifier build FAILED"; exit 1; }
IV="dotnet $HOME/.cache/ivtool/IntegrityVerifier.dll"
$IV "$OUT/StickyNotesPro.exe" "$PIN" || { echo "integrity gate FAILED"; exit 1; }

# tamper tests
T="$(mktemp -d)"
cp "$OUT/StickyNotesPro.exe" "$T/patched.exe";  printf '\x90' | dd of="$T/patched.exe" bs=1 seek=$((0x600)) conv=notrunc status=none
cp "$OUT/StickyNotesPro.exe" "$T/appended.exe"; printf 'MALWARE' >> "$T/appended.exe"
openssl req -new -x509 -newkey rsa:2048 -nodes -keyout "$T/k" -out "$T/c" \
    -subj "/CN=StickyNotes Pro Release Signing" -days 2 2>/dev/null
osslsigncode remove-signature -in "$OUT/StickyNotesPro.exe" -out "$T/unsigned.exe" >/dev/null
osslsigncode sign -certs "$T/c" -key "$T/k" -h sha256 -in "$T/unsigned.exe" -out "$T/foreign.exe" >/dev/null
for t in patched appended unsigned foreign; do
    if $IV "$T/$t.exe" "$PIN" >/dev/null 2>&1; then echo "tamper test $t FAILED (accepted!)"; exit 1; fi
    echo "   tamper test: $t -> rejected ✔"
done
rm -rf "$T"

EXE_SHA256="$(sha256sum "$OUT/StickyNotesPro.exe" | awk '{print toupper($1)}')"

# ---------------------------------------------------------------- installer
echo "-- building installer (EXE_SHA256=$EXE_SHA256)"
cp "$OUT/StickyNotesPro.exe" "$ROOT/StickyNotesPro.exe"
cp "$SRC/StickyNotesPro.exe.config" "$ROOT/StickyNotesPro.exe.config" 2>/dev/null || true
( cd "$ROOT/installer" && makensis -V2 -DSIGNSCRIPT="$BUILD/sign-file.sh" -DEXE_SHA256="$EXE_SHA256" setup.nsi )
SETUP="$ROOT/StickyNotesPro_Setup_$VERSION.exe"
[ -f "$SETUP" ] || { echo "installer build FAILED"; exit 1; }
osslsigncode verify -CAfile "$CERT_TMP" -in "$SETUP" > "$OUT/verify-setup.txt" 2>&1 \
    || { echo "installer signature verification FAILED"; exit 1; }
$IV "$SETUP" "$PIN" >/dev/null || { echo "installer integrity gate FAILED"; exit 1; }

# ---------------------------------------------------------------- release folder
REL="$ROOT/release/$VERSION"
mkdir -p "$REL"
cp "$OUT/StickyNotesPro.exe" "$REL/"
cp "$SRC/StickyNotesPro.exe.config" "$REL/" 2>/dev/null || true
cp "$SETUP" "$REL/"
openssl x509 -in "$CERT_TMP" -outform DER -out "$REL/StickyNotesPro-Release-Signing.cer"
sed -e "s/__PIN__/$PIN/g" -e "s/__EXE_SHA256__/$EXE_SHA256/g" -e "s/__VERSION__/$VERSION/g" \
    "$BUILD/Verify-StickyNotesPro.ps1" > "$REL/Verify-StickyNotesPro.ps1"

PYTHONPATH="${PYTHONPATH:-}" "$PY" "$BUILD/integrity_record.py" \
    --version "$VERSION" --exe "$REL/StickyNotesPro.exe" --setup "$REL/$(basename "$SETUP")" \
    --cert "$CERT_TMP" --pin "$PIN" --verify-log "$OUT/verify.txt" --out-dir "$REL" \
    ${SNP_PFX:+--pfx "$SNP_PFX"} ${SNP_PFX_PASS_FILE:+--passfile "$SNP_PFX_PASS_FILE"} ${SNP_TSA:+--tsa "$SNP_TSA"}

( cd "$REL" && sha256sum -- *.exe *.config *.cer *.ps1 *.json *.pdf \
    | awk '{print toupper($1) "  " $2}' > SHA256SUMS.txt )

rm -f "$CERT_TMP"
echo "== done: $REL"
ls -la "$REL"
